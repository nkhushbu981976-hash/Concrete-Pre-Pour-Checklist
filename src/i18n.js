export function translate(value, language = 'en') {
  if (language !== 'ja' || typeof value !== 'string') return value
  const defaultTemplate = value.match(/^(Slab|Beam|Column|Footing) (Standard|Detailed)$/)
  if (defaultTemplate) return `${translate(defaultTemplate[1], language)} ${translate(defaultTemplate[2], language)}`
  if (ja[value] !== undefined) return ja[value]
  return value
}

export function localizeItem(item, language = 'en') {
  if (language !== 'ja') return item
  return {
    ...item,
    category: translate(item.category, language),
    requirement: translate(item.requirement, language),
    criteria: translate(item.criteria, language),
    subChecks: (item.subChecks || []).map(check => ({ ...check, label: translate(check.label, language) })),
  }
}

export function translateMessage(value, language = 'en') {
  if (language !== 'ja' || !value) return value
  const known = translate(value, language)
  if (known !== value) return known
  if (value.startsWith('Reference PDF unavailable: ')) return value.replace('Reference PDF unavailable: ', '参考PDFを利用できません：')
  if (value.startsWith('Reference PDF failed: ')) return value.replace('Reference PDF failed: ', '参考PDFの処理に失敗しました：')
  if (value.startsWith('Print Preview failed: ')) return value.replace('Print Preview failed: ', '印刷プレビューを開けませんでした：')
  if (value === 'Print Preview did not open. Try the browser menu to print or save as PDF.') return '印刷プレビューが開きませんでした。ブラウザーのメニューから印刷またはPDF保存をお試しください。'
  const failedPhotoCount = value.match(/^(\d+) photos? could not be loaded/)
  if (failedPhotoCount) return `${failedPhotoCount[1]} 枚の写真を読み込めませんでした。レポートでは利用できない写真を表示します。`
  if (value.startsWith('Some photos could not be prepared: ')) return value.replace('Some photos could not be prepared: ', '一部の写真を準備できませんでした：')
  if (value.startsWith('Save Reference PDF')) return value.replace('Saving Reference PDF…', '参考PDFを保存中…')
  if (value.startsWith('Backup ready · ')) return value.replace('Backup ready · ', 'バックアップ準備完了 · ').replace(' photos included', ' 枚の写真を含む')
  if (value.startsWith('Backup failed: ')) return value.replace('Backup failed: ', 'バックアップ失敗：')
  if (value.startsWith('Restore failed: ')) return value.replace('Restore failed: ', '復元失敗：')
  if (value.startsWith('Save Failed — ')) return value.replace('Save Failed — ', '保存失敗 — ')
  const newerVersion = value.match(/^Saved data version (\d+) is newer than this application\. It has been preserved and will not be overwritten\.$/)
  if (newerVersion) return `保存データのバージョン ${newerVersion[1]} はこのアプリより新しいため、保持され上書きされません。`
  if (value === 'Saved inspection data could not be read.') return '保存済み検査データを読み込めませんでした。'
  if (value === 'Saved inspection data has an invalid format.') return '保存済み検査データの形式が正しくありません。'
  if (value.startsWith('Some evidence could not be prepared for printing: ')) return value.replace('Some evidence could not be prepared for printing: ', '印刷用の証拠を準備できませんでした：')
  if (value.startsWith('Could not add photo: ')) return value.replace('Could not add photo: ', '写真を追加できませんでした：')
  if (value.startsWith('Save Failed — photo was not attached: ')) return value.replace('Save Failed — photo was not attached: ', '保存失敗 — 写真を添付できませんでした：')
  return value
}

export function translateConfirm(value, language = 'en') {
  if (language !== 'ja') return value
  if (value.startsWith('Restore this ConcreteCheck backup?')) {
    const summary = value.split('\n\n')[1] || ''
    const counts = summary.match(/(\d+) active items, (\d+) history records and (\d+) photos/)
    const localizedSummary = counts ? `${counts[1]} 件の検査項目、${counts[2]} 件の履歴、${counts[3]} 枚の写真` : summary
    return `${translate('Restore this ConcreteCheck backup?', language)}\n\n${localizedSummary}\n\n${translate('Current data will be replaced. A recovery copy will be preserved first.', language)}`
  }
  if (value.startsWith('Remove the archived inspection')) {
    const label = value.match(/“([^”]+)”/)?.[1] || ''
    return `履歴から保存済み検査「${label}」を削除しますか？現在の検査には影響しません。`
  }
  return translate(value, language)
}
